/**
 * Generează packages/pdf/src/tokens.generated.ts din docs/design/system/tokens.json.
 * PDF-ul are o singură temă: light. Dimensiunile trec din px în pt (1px CSS = 0,75pt).
 * `lineHeight` iese ca raport (react-pdf înmulțește numerele fără unitate cu fontSize).
 * Run: node packages/pdf/scripts/generate-tokens.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dir = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dir, '..', '..', '..');
const tokensPath = join(repoRoot, 'docs', 'design', 'system', 'tokens.json');
const outPath = join(__dir, '..', 'src', 'tokens.generated.ts');

const PT_PER_PX = 0.75;
const FAMILIES = { sans: 'DM Sans', display: 'Syne' };

const round = (n) => Math.round(n * 1000) / 1000;

function px(value) {
  const m = /^(-?[\d.]+)px$/.exec(value);
  if (!m) throw new Error(`Valoare fără px: ${value}`);
  return Number(m[1]);
}

export function buildPdfTokens(tokens) {
  const raw = Object.fromEntries(
    tokens.color.tokens.map((t) => [t.name, typeof t.value === 'string' ? t.value : t.value.light]),
  );
  const resolve = (value, seen = []) => {
    const m = /^\{(.+)\}$/.exec(value);
    if (!m) return value;
    if (seen.includes(m[1])) throw new Error(`Referință circulară: ${m[1]}`);
    return resolve(raw[m[1]], [...seen, m[1]]);
  };
  const color = Object.fromEntries(Object.entries(raw).map(([k, v]) => [k, resolve(v)]));

  const type = {};
  for (const group of tokens.type.groups) {
    for (const s of group.styles) {
      const size = px(s.fontSize);
      const em = s.letterSpacing ? Number(String(s.letterSpacing).replace('em', '')) : 0;
      type[s.name] = {
        fontFamily: FAMILIES[group.family],
        fontSize: round(size * PT_PER_PX),
        lineHeight: round(px(s.lineHeight) / size),
        fontWeight: s.fontWeight,
        letterSpacing: round(em * size * PT_PER_PX),
      };
    }
  }

  const pt = (list) =>
    Object.fromEntries(list.map((t) => [t.name, round(px(t.value) * PT_PER_PX)]));

  return {
    color,
    type,
    space: pt(tokens.spacing.tokens),
    radius: pt(tokens.radius.tokens.filter((t) => /px$/.test(t.value))),
    border: pt(tokens.border.tokens.filter((t) => /px$/.test(t.value))),
  };
}

export function renderTokensModule(pdfTokens) {
  return [
    '/* Generated by packages/pdf/scripts/generate-tokens.mjs — do not edit */',
    '/* Sursa: docs/design/system/tokens.json, tema light, px → pt */',
    '',
    `export const pdfTokens = ${JSON.stringify(pdfTokens, null, 2)} as const;`,
    '',
    'export type PdfColorToken = keyof typeof pdfTokens.color;',
    'export type PdfTypeStyle = keyof typeof pdfTokens.type;',
    '',
  ].join('\n');
}

export function generate() {
  const tokens = JSON.parse(readFileSync(tokensPath, 'utf-8'));
  return renderTokensModule(buildPdfTokens(tokens));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(outPath, generate());
  console.log(`✓ ${outPath}`);
}
