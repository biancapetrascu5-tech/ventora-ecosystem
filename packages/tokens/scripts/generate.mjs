/**
 * Generates packages/tokens/business/tokens.css, business/fonts.css, business/types.ts
 * from docs/design/system/tokens.json.
 * Run: node packages/tokens/scripts/generate.mjs
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dir = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dir, '..', '..', '..');
const tokensPath = join(repoRoot, 'docs', 'design', 'system', 'tokens.json');
const outDir = join(__dir, '..', 'business');

mkdirSync(outDir, { recursive: true });
mkdirSync(join(__dir, '..', 'portal'), { recursive: true });
mkdirSync(join(__dir, '..', 'network'), { recursive: true });

const tokens = JSON.parse(readFileSync(tokensPath, 'utf-8'));

// ── CSS generation ────────────────────────────────────────────────────────────

const lightVars = [];
const darkVars = [];
const staticVars = [];

function resolveRef(value) {
  if (typeof value === 'string') {
    const m = value.match(/^\{(.+)\}$/);
    return m ? `var(--${m[1]})` : value;
  }
  return value;
}

function pushThemed(name, value) {
  if (typeof value === 'string') {
    const resolved = resolveRef(value);
    lightVars.push(`  --${name}: ${resolved};`);
    darkVars.push(`  --${name}: ${resolved};`);
    return;
  }
  lightVars.push(`  --${name}: ${value.light};`);
  darkVars.push(`  --${name}: ${value.dark};`);
}

function pushStatic(name, value) {
  staticVars.push(`  --${name}: ${value};`);
}

// Colors
staticVars.push('  /* colors */');
for (const t of tokens.color.tokens) {
  pushThemed(t.name, t.value);
}

// Shadows
staticVars.push('  /* shadows */');
for (const t of tokens.shadow.tokens) {
  pushThemed(t.name, t.value);
}

// Font families
staticVars.push('  /* font families */');
pushStatic('font-sans', tokens.type.families.sans);
pushStatic('font-display', tokens.type.families.display);

// Typography scale
staticVars.push('  /* typography scale */');
for (const group of tokens.type.groups) {
  const familyVar = group.family === 'display' ? 'var(--font-display)' : 'var(--font-sans)';
  for (const style of group.styles) {
    pushStatic(`type-${style.name}-size`, style.fontSize);
    pushStatic(`type-${style.name}-line`, style.lineHeight);
    pushStatic(`type-${style.name}-weight`, String(style.fontWeight));
    if (style.letterSpacing) {
      pushStatic(`type-${style.name}-tracking`, style.letterSpacing);
    }
    pushStatic(`type-${style.name}-family`, familyVar);
  }
}

// Spacing
staticVars.push('  /* spacing */');
for (const t of tokens.spacing.tokens) {
  pushStatic(t.name, t.value);
}

// Radius
staticVars.push('  /* radius */');
for (const t of tokens.radius.tokens) {
  pushStatic(t.name, t.value);
}

// Border
staticVars.push('  /* border */');
for (const t of tokens.border.tokens) {
  pushStatic(t.name, t.value);
}

// Size
staticVars.push('  /* size */');
for (const t of tokens.size.tokens) {
  pushStatic(t.name, t.value);
}

// Duration
staticVars.push('  /* duration */');
for (const t of tokens.duration.tokens) {
  pushStatic(t.name, t.value);
}

// Easing
staticVars.push('  /* easing */');
for (const t of tokens.easing.tokens) {
  pushStatic(t.name, t.value);
}

// Z-index
staticVars.push('  /* z-index */');
for (const t of tokens.zIndex.tokens) {
  pushStatic(t.name, t.value);
}

// Separate light/dark vars from "static" vars that were pushed as comments
const lightSection = lightVars.join('\n');
const darkSection = darkVars.join('\n');
const allRootVars = [...staticVars].join('\n');

const tokensCss = `/* Generated by packages/tokens/scripts/generate.mjs — do not edit */

:root {
  color-scheme: light;
${lightSection}
${allRootVars}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${darkSection.replace(/^/gm, '  ')}
  }
}

:root[data-theme="dark"] {
  color-scheme: dark;
${darkSection}
}
`;

writeFileSync(join(outDir, 'tokens.css'), tokensCss, 'utf-8');
console.log('✓ business/tokens.css');

// ── Fonts CSS ─────────────────────────────────────────────────────────────────

const fontFaces = tokens.type.fonts
  .map((f) => {
    const src = `url('../fonts/${f.file.replace('fonts/', '')}') format('woff2')`;
    return `@font-face {
  font-family: '${f.family}';
  src: ${src};
  font-weight: ${f.weight};
  font-style: ${f.style};
  font-display: swap;
}`;
  })
  .join('\n\n');

const fontsCss = `/* Generated by packages/tokens/scripts/generate.mjs — do not edit */

${fontFaces}
`;

writeFileSync(join(outDir, 'fonts.css'), fontsCss, 'utf-8');
console.log('✓ business/fonts.css');

// ── TypeScript types ──────────────────────────────────────────────────────────

function toUnion(names) {
  return names.map((n) => `  | '${n}'`).join('\n');
}

const colorNames = tokens.color.tokens.map((t) => t.name);
const spaceNames = tokens.spacing.tokens.map((t) => t.name);
const radiusNames = tokens.radius.tokens.map((t) => t.name);
const borderNames = tokens.border.tokens.map((t) => t.name);
const shadowNames = tokens.shadow.tokens.map((t) => t.name);
const sizeNames = tokens.size.tokens.map((t) => t.name);
const durationNames = tokens.duration.tokens.map((t) => t.name);
const easingNames = tokens.easing.tokens.map((t) => t.name);
const zIndexNames = tokens.zIndex.tokens.map((t) => t.name);
const typeNames = tokens.type.groups.flatMap((g) => g.styles.map((s) => s.name));

const typeScaleTs = `/* Generated by packages/tokens/scripts/generate.mjs — do not edit */

export type ColorToken =
${toUnion(colorNames)};

export type SpaceToken =
${toUnion(spaceNames)};

export type RadiusToken =
${toUnion(radiusNames)};

export type BorderToken =
${toUnion(borderNames)};

export type ShadowToken =
${toUnion(shadowNames)};

export type SizeToken =
${toUnion(sizeNames)};

export type DurationToken =
${toUnion(durationNames)};

export type EasingToken =
${toUnion(easingNames)};

export type ZIndexToken =
${toUnion(zIndexNames)};

export type TypeToken =
${toUnion(typeNames)};

export type AnyToken =
  | ColorToken
  | SpaceToken
  | RadiusToken
  | BorderToken
  | ShadowToken
  | SizeToken
  | DurationToken
  | EasingToken
  | ZIndexToken
  | TypeToken;
`;

writeFileSync(join(outDir, 'types.ts'), typeScaleTs, 'utf-8');
console.log('✓ business/types.ts');

// ── Portal / Network placeholders ─────────────────────────────────────────────

const placeholderNote = (brand) => `/* ${brand} token overrides — not yet implemented (F2+) */\n`;

writeFileSync(join(__dir, '..', 'portal', 'tokens.css'), placeholderNote('Portal'), 'utf-8');
writeFileSync(join(__dir, '..', 'network', 'tokens.css'), placeholderNote('Network'), 'utf-8');
console.log('✓ portal/tokens.css (placeholder)');
console.log('✓ network/tokens.css (placeholder)');

console.log('\nDone.');
