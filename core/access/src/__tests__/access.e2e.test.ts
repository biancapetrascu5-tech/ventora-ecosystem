import { describe, it, expect, beforeAll, afterAll } from 'vitest';
import { Pool } from 'pg';
import { hubAuth } from '@ventora/identity';
import { authorize, acceptInvitationWithAccess, configureAccess } from '../index.js';
import { resolveOrgContext, inviteMember } from '@ventora/organizations';

const adminPool = new Pool({
  connectionString: process.env.DIRECT_URL || process.env.DATABASE_URL,
  max: 2,
});

async function adminQuery(sql: string, params: unknown[] = []) {
  const client = await adminPool.connect();
  try {
    return await client.query(sql, params);
  } finally {
    client.release();
  }
}

function newUuid(): string {
  return crypto.randomUUID();
}

// Signs up via the Better Auth API directly (same pattern as identity integration tests).
// Returns the userId generated by Better Auth (must be UUID after the generateId fix)
// and the session token usable as a Bearer token.
async function signUpViaAuth(
  email: string,
  password: string,
): Promise<{ userId: string; sessionToken: string }> {
  const result = await hubAuth.api.signUpEmail({
    body: { email, password, name: email.split('@')[0] },
  });
  const userId: string = result?.user?.id ?? '';
  const sessionToken: string = result?.token ?? '';
  return { userId, sessionToken };
}

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

let orgId: string;
let ownerEmail: string;
let inviteeEmail: string;
let ownerUserId: string;
let ownerToken: string;

beforeAll(() => {
  configureAccess({ entitlementProvider: { isEnabled: async () => true } });
});

afterAll(async () => {
  if (orgId) {
    await adminQuery(`DELETE FROM organizations.organization WHERE id = $1`, [orgId]);
  }
  if (ownerEmail) {
    await adminQuery(`DELETE FROM identity.users WHERE email = $1`, [ownerEmail]);
  }
  if (inviteeEmail) {
    await adminQuery(`DELETE FROM identity.users WHERE email = $1`, [inviteeEmail]);
  }
  await adminPool.end();
});

describe('E2E — Better Auth UUID IDs', () => {
  it('sign-up via Better Auth generates UUID-format userId', async () => {
    ownerEmail = `e2e-owner-${newUuid()}@test.local`;
    const result = await signUpViaAuth(ownerEmail, 'SecurePass123!');
    ownerUserId = result.userId;
    ownerToken = result.sessionToken;

    expect(ownerUserId).toBeTruthy();
    expect(UUID_RE.test(ownerUserId)).toBe(true);
    expect(ownerToken).toBeTruthy();
  });

  it('full flow: createOrg → invite → acceptInvitationWithAccess → authorize', async () => {
    // Create org + owner membership via adminQuery (founder flow not needed for this test)
    orgId = newUuid();
    await adminQuery(
      `INSERT INTO organizations.organization (id, slug, name, created_via, updated_at)
       VALUES ($1::uuid, $2, $3, 'self_service', NOW())`,
      [orgId, `e2e-${orgId.slice(0, 8)}`, `E2E Org ${orgId.slice(0, 8)}`],
    );
    const ownerMemId = newUuid();
    await adminQuery(
      `INSERT INTO organizations.membership (id, organization_id, user_id, role, status, updated_at)
       VALUES ($1::uuid, $2::uuid, $3::uuid, 'owner', 'active', NOW())`,
      [ownerMemId, orgId, ownerUserId],
    );

    // Set owner session active org
    await adminQuery(
      `UPDATE identity.sessions SET active_organization_id = $1::uuid WHERE token = $2`,
      [orgId, ownerToken],
    );

    // Resolve OrgContext for owner (needed by inviteMember)
    const ownerOrgCtx = await resolveOrgContext({ userId: ownerUserId, organizationId: orgId });

    // Sign up invitee — userId must also be a UUID
    inviteeEmail = `e2e-invitee-${newUuid()}@test.local`;
    const { userId: inviteeUserId, sessionToken: inviteeToken } = await signUpViaAuth(
      inviteeEmail,
      'InviteePass456!',
    );
    expect(UUID_RE.test(inviteeUserId)).toBe(true);

    // Invite the invitee (applicationIds includes 'booking' so grant fires)
    const { invitationToken } = await inviteMember(ownerOrgCtx, {
      email: inviteeEmail,
      role: 'member',
      inviterName: 'E2E Owner',
      organizationName: `E2E Org ${orgId.slice(0, 8)}`,
      applicationIds: ['booking'],
    });

    // Accept with REAL userId — would fail with non-UUID ID before the fix
    const acceptResult = await acceptInvitationWithAccess({
      token: invitationToken,
      userId: inviteeUserId,
      userEmail: inviteeEmail,
    });
    expect(acceptResult.organizationId).toBe(orgId);
    expect(acceptResult.role).toBe('member');

    // Set invitee session active org
    await adminQuery(
      `UPDATE identity.sessions SET active_organization_id = $1::uuid WHERE token = $2`,
      [orgId, inviteeToken],
    );

    // authorize() — invitee has booking access via application_access row
    const ctx = await authorize({
      sessionToken: inviteeToken,
      applicationId: 'booking',
    });
    expect(ctx.userId).toBe(inviteeUserId);
    expect(ctx.organizationId).toBe(orgId);
    expect(ctx.role).toBe('member');
  });
});
